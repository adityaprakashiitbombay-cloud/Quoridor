export function getCampaignLevel(levelNumber: number): CampaignLevelConfig {
  const found = CAMPAIGN_LEVELS.find((l) => l.levelNumber === levelNumber);
  return found || CAMPAIGN_LEVELS[0];
}

export function getStarsForLevel(movesTaken: number, parMoves: number, isWin: boolean): number {
  if (!isWin) return 0;
  if (movesTaken <= parMoves) return 3;
  if (movesTaken <= parMoves + 5) return 2;
  return 1;
}
