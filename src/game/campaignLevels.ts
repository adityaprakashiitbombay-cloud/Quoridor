// Helper to construct pre-placed neutral walls
function createWall(id: string, x: number, y: number, orientation: 'H' | 'V'): Wall {
  return {
    id,
    x,
    y,
    orientation,
    placedBy: -1, // -1 denotes neutral/pre-placed puzzle barrier
  };
}

